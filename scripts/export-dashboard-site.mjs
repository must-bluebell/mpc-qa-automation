#!/usr/bin/env node
// Export a read-only, sanitized snapshot of recent completed QA runs for a static host such as Vercel.
// Usage: node scripts/export-dashboard-site.mjs [--out vercel-site] [--limit 50]
// Only publicSummary() output is written. Raw run.json, logs, traces, screenshots and .env never leave runs/.
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'
import { pathToFileURL } from 'node:url'
import { ROOT, knownSecrets } from '../pipeline/lib/env.mjs'
import { isRunId, readIndex, readRun } from '../pipeline/lib/run-store.mjs'
import { publicSummary } from '../pipeline/lib/safe-output.mjs'

const SITE_SOURCE = join(ROOT, 'dashboard', 'read-only')
const STYLE_SOURCE = join(ROOT, 'dashboard', 'public', 'style.css')
const DEFAULT_LIMIT = 50
const MAX_LIMIT = 200
const MARKER = '.qa-site-export'

// Runs the dashboard hides from its own category results: still in progress, skipped, seeded-defect or report-only.
const excluded = entry => !entry.finishedAt || ['running', 'skipped-overlap'].includes(entry.status) || entry.seededDefect || entry.reportOnly

function headerOf(summary) {
  return {
    runId: summary.runId, suite: summary.suite, environment: summary.environment, status: summary.status,
    finishedAt: summary.finishedAt, applicationVersion: summary.applicationVersion, counts: summary.counts, quality: summary.quality,
  }
}

// Only a folder this exporter made (marked, or empty) may be replaced.
function assertSafeOutDir(outDir) {
  if (outDir === ROOT || !resolve(outDir).startsWith(ROOT + sep)) throw new Error(`Output must be a folder inside ${ROOT}`)
  let current = ROOT
  for (const part of relative(ROOT, outDir).split(sep)) {
    current = join(current, part)
    if (existsSync(current) && lstatSync(current).isSymbolicLink()) throw new Error(`Refusing to export through a symlink: ${current}`)
  }
  if (existsSync(outDir) && (!lstatSync(outDir).isDirectory() || (readdirSync(outDir).length && !existsSync(join(outDir, MARKER)))))
    throw new Error(`Refusing to replace ${outDir}: it is not a previous site export`)
}

/** Builds the site into outDir. Returns the number of runs exported. */
export function exportSite({ outDir, limit = DEFAULT_LIMIT, index = readIndex(), loadRun = readRun }) {
  assertSafeOutDir(outDir)

  const summaries = []
  const candidates = index
    .filter(entry => isRunId(entry.runId) && !excluded(entry))
    .sort((a, b) => Date.parse(b.finishedAt) - Date.parse(a.finishedAt))
  for (const entry of candidates) {
    if (summaries.length >= limit) break
    const run = loadRun(entry.runId)
    if (!run || excluded(run)) continue
    // The ID becomes a filename, so it must match the validated index entry rather than whatever the record claims.
    const summary = publicSummary(run)
    if (summary.runId !== entry.runId) continue
    summaries.push(summary)
  }

  const generatedAt = new Date().toISOString()
  const files = new Map([
    [join('data', 'runs.json'), JSON.stringify({ generatedAt, runs: summaries.map(headerOf) }, null, 2)],
    ...summaries.map(s => [join('data', 'runs', `${s.runId}.json`), JSON.stringify(s)]),
  ])

  // Last line of defence: a secret in any exported byte means the sanitizer missed something, so nothing is written.
  const secrets = knownSecrets()
  for (const [file, text] of files) {
    const leaked = secrets.find(secret => text.includes(secret))
    if (leaked) throw new Error(`Refusing to export: a configured secret appeared in ${file}`)
  }

  mkdirSync(dirname(outDir), { recursive: true })
  const staging = mkdtempSync(join(dirname(outDir), `.${basename(outDir)}-`))
  const next = join(staging, 'next'), previous = join(staging, 'previous')
  try {
    cpSync(SITE_SOURCE, next, { recursive: true })
    cpSync(STYLE_SOURCE, join(next, 'style.css'))
    mkdirSync(join(next, 'data', 'runs'), { recursive: true })
    writeFileSync(join(next, MARKER), 'Generated by scripts/export-dashboard-site.mjs. Safe to replace.\n')
    for (const [file, text] of files) writeFileSync(join(next, file), text)
    const hadPrevious = existsSync(outDir)
    if (hadPrevious) renameSync(outDir, previous)
    try { renameSync(next, outDir) }
    catch (error) {
      if (hadPrevious) renameSync(previous, outDir)
      throw error
    }
  } finally {
    // Keep the backup if restoring it failed, so the last valid snapshot is never deleted.
    if (!existsSync(previous) || existsSync(outDir)) rmSync(staging, { recursive: true, force: true })
  }
  return summaries.length
}

function parseArgs(argv) {
  const args = { out: 'vercel-site', limit: DEFAULT_LIMIT }
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') args.out = argv[++i]
    else if (argv[i] === '--limit') args.limit = Number(argv[++i])
    else throw new Error(`Unknown argument: ${argv[i]}`)
  }
  if (!Number.isInteger(args.limit) || args.limit < 1 || args.limit > MAX_LIMIT) throw new Error(`--limit must be 1-${MAX_LIMIT}`)
  return args
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = parseArgs(process.argv.slice(2))
  const outDir = resolve(ROOT, args.out)
  const count = exportSite({ outDir, limit: args.limit })
  console.log(`Exported ${count} run(s) to ${outDir}`)
  console.log('Preview locally: npx --yes serve ' + outDir)
}
